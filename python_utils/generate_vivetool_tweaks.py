# ──────────────────────────────────────────────────────────────────────
# Батник сам ищет ViVeTool.exe вверх по дереву (1..5 уровней).
# Больше не зависит от глубины вложенности папки.
# ──────────────────────────────────────────────────────────────────────
BAT_TEMPLATE = """@echo off
setlocal enableextensions
title {title}
set "VIVETOOL="
for %%D in ("%~dp0.." "%~dp0..\\.." "%~dp0..\\..\\.." "%~dp0..\\..\\..\\.." "%~dp0..\\..\\..\\..\\..") do (
  if not defined VIVETOOL if exist "%%~fD\\Utils\\ViVeTool\\ViVeTool.exe" set "VIVETOOL=%%~fD\\Utils\\ViVeTool\\ViVeTool.exe"
)
if not defined VIVETOOL (
  echo [ERROR] ViVeTool.exe не найден
  exit /b 1
)
"%VIVETOOL%" /{verb} /id:{ids}
if errorlevel 1 (
  echo [ERROR] ViVeTool вернул ошибку
  exit /b 1
)
echo OK
exit /b 0
"""

def make_bat(title, verb, ids):
    """Генерирует содержимое .bat файла."""
    return BAT_TEMPLATE.format(
        title=title,
        verb=verb,
        ids=",".join(ids)
    )

def write_file(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\r\n") as f:
        f.write(text)

