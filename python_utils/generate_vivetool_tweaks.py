def generate(version: str, tweaks: list):
    """
    Генерирует .bat файлы и JSON для указанной версии Windows.
    Больше не нужно передавать depth_up — батник сам ищет ViVeTool.
    """
    base = ROOT / "tweaks" / "Кастомизация" / f"Windows {version}"
    cancel = base / "отмена"
    base.mkdir(parents=True, exist_ok=True)
    cancel.mkdir(parents=True, exist_ok=True)

    enabled, cancelled = [], []
    for name, ids, _desc in tweaks:
        on_file = f"Включить {name}.bat"
        write_file(base / on_file, make_bat(f"Включить: {name}", "enable", ids))
        enabled.append(on_file)

        off_file = f"Выключить {name}.bat"
        write_file(cancel / off_file, make_bat(f"Выключить: {name}", "disable", ids))
        cancelled.append(off_file)

    data = {"tabs": {"Root": enabled, "отмена": cancelled}}
    out = JSON_DIR / f"vivetool_{version.lower()}_tabs.json"
    with open(out, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"[OK] {version}: {len(enabled)} твиков -> {out}")

def main():
    generate("25H2", TWEAKS_COMMON)
    generate("26H2", TWEAKS_COMMON + TWEAKS_26H2_ONLY)

if __name__ == "__main__":
    main()